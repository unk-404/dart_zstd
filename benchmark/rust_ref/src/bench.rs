//! `bench` — libzstd reference measurements for the zstd_neo benchmark card.
//!
//! The output is canonical JSONL (one result object per line) with the same
//! ids the Dart `benchmark_test` suite reports:
//!
//! * `compress.<corpus>.l3` / `.l9` / `.l19` — MiB/s of plaintext;
//! * `decompress.<corpus>.l3` / `.l19` — MiB/s of plaintext, from the
//!   committed level-3 and level-19 frames;
//! * `ratio.<corpus>.l3` / `.l9` / `.l19` — compressed / original, lower is
//!   better.
//!
//! The measurement loop is deliberately small: three warm-up iterations,
//! then repetitions until at least 300 ms elapsed or 200 repetitions. The
//! reported `stats.rme_pct` is the approximate 95% relative margin of error
//! of the per-iteration times.

use std::error::Error;
use std::fs;
use std::hint::black_box;
use std::path::PathBuf;
use std::time::{Duration, Instant};

use crate::bench_data::{json_string, parse_manifest, ManifestEntry};
use crate::decode_bytes;

const MIB: f64 = 1024.0 * 1024.0;
const WARMUP_REPS: usize = 3;
const MAX_REPS: usize = 200;
const TARGET_DURATION: Duration = Duration::from_millis(300);

pub const USAGE: &str = "\
zstd_ref bench [--data DIR] [--out FILE]

Reads manifest.json and the slices generated by `bench-data`, measures
libzstd compression at levels 3, 9 and 19, decompression of the level-3 and
level-19 frames, and the level-3/9/19 ratios, then writes canonical JSONL.

defaults:
    --data  benchmark/bench_data
    --out   build/bench/series-rust.jsonl
";

struct Measure {
    /// Mean time per operation, in seconds.
    mean_seconds: f64,
    /// Approximate 95% relative margin of error, in percent.
    rme_pct: f64,
    samples: usize,
    /// Last value returned by the measured operation (used for ratios).
    last_output: usize,
}

struct CorpusResult {
    entry: ManifestEntry,
    compress_l3: Measure,
    compress_l9: Measure,
    compress_l19: Measure,
    decompress_l3: Measure,
    decompress_l19: Measure,
    compressed_l3_bytes: usize,
    compressed_l9_bytes: usize,
    compressed_l19_bytes: usize,
}

fn parse_args(args: &[String]) -> Result<(PathBuf, PathBuf), Box<dyn Error>> {
    let mut data = PathBuf::from("benchmark/bench_data");
    let mut out = PathBuf::from("build/bench/series-rust.jsonl");
    let mut index = 0;
    while index < args.len() {
        let arg = args[index].as_str();
        match arg {
            "--data" | "--out" => {
                index += 1;
                let value = args
                    .get(index)
                    .cloned()
                    .ok_or_else(|| format!("{arg} needs a value"))?;
                match arg {
                    "--data" => data = PathBuf::from(value),
                    "--out" => out = PathBuf::from(value),
                    _ => unreachable!(),
                }
            }
            "--help" | "-h" => {
                println!("{USAGE}");
                std::process::exit(0);
            }
            other => return Err(format!("unknown option `{other}`\n\n{USAGE}").into()),
        }
        index += 1;
    }
    Ok((data, out))
}

fn measure<F, E>(mut op: F) -> Result<Measure, E>
where
    F: FnMut() -> Result<usize, E>,
{
    for _ in 0..WARMUP_REPS {
        black_box(op()?);
    }

    let mut durations = Vec::with_capacity(MAX_REPS);
    let started = Instant::now();
    let mut last_output = 0;
    while durations.len() < MAX_REPS {
        let iteration = Instant::now();
        last_output = op()?;
        durations.push(iteration.elapsed().as_secs_f64());
        if started.elapsed() >= TARGET_DURATION {
            break;
        }
    }
    black_box(last_output);

    let count = durations.len();
    let sum: f64 = durations.iter().sum();
    let mean = sum / count as f64;
    let variance = if count > 1 {
        durations
            .iter()
            .map(|duration| (duration - mean).powi(2))
            .sum::<f64>()
            / (count - 1) as f64
    } else {
        0.0
    };
    let standard_error = (variance / count as f64).sqrt();
    let rme_pct = if mean > 0.0 {
        1.96 * standard_error / mean * 100.0
    } else {
        0.0
    };

    Ok(Measure {
        mean_seconds: mean,
        rme_pct,
        samples: count,
        last_output,
    })
}

fn throughput_mib_per_second(plain_bytes: usize, measure: &Measure) -> f64 {
    (plain_bytes as f64 / MIB) / measure.mean_seconds
}

fn measure_compress(level: i32, plain: &[u8]) -> Result<(Measure, usize), Box<dyn Error>> {
    let mut compressor = zstd::bulk::Compressor::new(level)?;
    let measurement = measure(|| compressor.compress(plain).map(|frame| frame.len()))?;
    let compressed_bytes = measurement.last_output;
    Ok((measurement, compressed_bytes))
}

fn measure_decompress(frame: &[u8], plain_len: usize) -> Result<Measure, Box<dyn Error>> {
    let mut decompressor = zstd::bulk::Decompressor::new()?;
    Ok(measure(|| {
        decompressor
            .decompress(frame, plain_len)
            .map(|out| out.len())
    })?)
}

fn push_throughput(
    lines: &mut Vec<String>,
    result: &CorpusResult,
    metric: &str,
    level: &str,
    group: &str,
    measurement: &Measure,
) {
    let label = result.entry.id.as_str();
    let id = format!("{metric}.{label}.{level}");
    let value = throughput_mib_per_second(result.entry.plain_bytes, measurement);
    lines.push(record(
        &id,
        group,
        label,
        "MiB/s",
        None,
        value,
        measurement.rme_pct,
        measurement.samples,
    ));
}

fn push_ratio(
    lines: &mut Vec<String>,
    result: &CorpusResult,
    level: &str,
    compressed_bytes: usize,
) {
    let label = result.entry.id.as_str();
    let id = format!("ratio.{label}.{level}");
    let ratio = compressed_bytes as f64 / result.entry.plain_bytes as f64;
    lines.push(record(
        &id,
        &format!("Ratio · L{}", level.trim_start_matches('l')),
        label,
        "x",
        Some("lower"),
        ratio,
        0.0,
        1,
    ));
}

pub fn run(args: &[String]) -> Result<(), Box<dyn Error>> {
    let (data_dir, out_path) = parse_args(args)?;
    let manifest_path = data_dir.join("manifest.json");
    let manifest = fs::read_to_string(&manifest_path)
        .map_err(|error| format!("{}: {error}", manifest_path.display()))?;
    let entries = parse_manifest(&manifest)
        .map_err(|error| format!("{}: {error}", manifest_path.display()))?;

    let expected_ids: Vec<&str> = crate::bench_data::CORPORA
        .iter()
        .map(|(id, _)| *id)
        .collect();
    let actual_ids: Vec<&str> = entries.iter().map(|entry| entry.id.as_str()).collect();
    if actual_ids != expected_ids {
        return Err(format!(
            "{}: expected corpora {:?}, found {:?}",
            manifest_path.display(),
            expected_ids,
            actual_ids
        )
        .into());
    }

    let mut results = Vec::with_capacity(entries.len());
    for entry in entries {
        let plain_path = data_dir.join(&entry.plain);
        let l3_path = data_dir.join(&entry.l3);
        let l19_path = data_dir.join(&entry.l19);
        let plain =
            fs::read(&plain_path).map_err(|error| format!("{}: {error}", plain_path.display()))?;
        let l3 = fs::read(&l3_path).map_err(|error| format!("{}: {error}", l3_path.display()))?;
        let l19 =
            fs::read(&l19_path).map_err(|error| format!("{}: {error}", l19_path.display()))?;

        if plain.len() != entry.plain_bytes || plain.len() != entry.bytes {
            return Err(format!(
                "{}: expected {} plaintext bytes, found {}",
                plain_path.display(),
                entry.plain_bytes,
                plain.len()
            )
            .into());
        }
        if l3.len() != entry.l3_bytes || l19.len() != entry.l19_bytes {
            return Err(format!(
                "{}: frame sizes do not match manifest.json",
                data_dir.display()
            )
            .into());
        }

        for (level, frame, path) in [(3, &l3, &l3_path), (19, &l19, &l19_path)] {
            let decoded = decode_bytes(frame, &[]).map_err(|error| {
                format!("{}: libzstd could not decode: {error}", path.display())
            })?;
            if decoded != plain {
                return Err(format!(
                    "{}: level-{level} frame does not decode to {}",
                    path.display(),
                    plain_path.display()
                )
                .into());
            }
        }

        let (compress_l3, compressed_l3_bytes) = measure_compress(3, &plain)?;
        let (compress_l9, compressed_l9_bytes) = measure_compress(9, &plain)?;
        let (compress_l19, compressed_l19_bytes) = measure_compress(19, &plain)?;
        let decompress_l3 = measure_decompress(&l3, plain.len())?;
        let decompress_l19 = measure_decompress(&l19, plain.len())?;

        let result = CorpusResult {
            entry,
            compress_l3,
            compress_l9,
            compress_l19,
            decompress_l3,
            decompress_l19,
            compressed_l3_bytes,
            compressed_l9_bytes,
            compressed_l19_bytes,
        };
        let plain_bytes = result.entry.plain_bytes;
        eprintln!(
            "zstd_ref: {:<7} compress L3/L9/L19 \
             {:>8.2}/{:>8.2}/{:>8.2} MiB/s  decompress L3/L19 \
             {:>8.2}/{:>8.2} MiB/s  ratio L3/L9/L19 \
             {:.4}/{:.4}/{:.4}",
            result.entry.id,
            throughput_mib_per_second(plain_bytes, &result.compress_l3),
            throughput_mib_per_second(plain_bytes, &result.compress_l9),
            throughput_mib_per_second(plain_bytes, &result.compress_l19),
            throughput_mib_per_second(plain_bytes, &result.decompress_l3),
            throughput_mib_per_second(plain_bytes, &result.decompress_l19),
            result.compressed_l3_bytes as f64 / plain_bytes as f64,
            result.compressed_l9_bytes as f64 / plain_bytes as f64,
            result.compressed_l19_bytes as f64 / plain_bytes as f64,
        );
        results.push(result);
    }

    let mut lines = Vec::with_capacity(results.len() * 8);
    for result in &results {
        push_throughput(
            &mut lines,
            result,
            "compress",
            "l3",
            "Compress · L3",
            &result.compress_l3,
        );
    }
    for result in &results {
        push_throughput(
            &mut lines,
            result,
            "compress",
            "l9",
            "Compress · L9",
            &result.compress_l9,
        );
    }
    for result in &results {
        push_throughput(
            &mut lines,
            result,
            "compress",
            "l19",
            "Compress · L19",
            &result.compress_l19,
        );
    }
    for result in &results {
        push_throughput(
            &mut lines,
            result,
            "decompress",
            "l3",
            "Decompress · L3",
            &result.decompress_l3,
        );
    }
    for result in &results {
        push_throughput(
            &mut lines,
            result,
            "decompress",
            "l19",
            "Decompress · L19",
            &result.decompress_l19,
        );
    }
    for result in &results {
        push_ratio(&mut lines, result, "l3", result.compressed_l3_bytes);
    }
    for result in &results {
        push_ratio(&mut lines, result, "l9", result.compressed_l9_bytes);
    }
    for result in &results {
        push_ratio(&mut lines, result, "l19", result.compressed_l19_bytes);
    }

    if let Some(parent) = out_path.parent() {
        fs::create_dir_all(parent)?;
    }
    let mut contents = lines.join("\n");
    contents.push('\n');
    fs::write(&out_path, contents)?;
    eprintln!(
        "zstd_ref: wrote {} canonical records to {}",
        lines.len(),
        out_path.display()
    );
    Ok(())
}

fn record(
    id: &str,
    group: &str,
    label: &str,
    unit: &str,
    direction: Option<&str>,
    value: f64,
    rme_pct: f64,
    samples: usize,
) -> String {
    let mut line = format!(
        "{{\"id\":{},\"group\":{},\"label\":{},\"unit\":{}",
        json_string(id),
        json_string(group),
        json_string(label),
        json_string(unit)
    );
    if let Some(direction) = direction {
        line.push_str(",\"direction\":");
        line.push_str(&json_string(direction));
    }
    line.push_str(&format!(
        ",\"value\":{value:.6},\"stats\":{{\"rme_pct\":{rme_pct:.4},\"samples\":{samples}}}}}"
    ));
    line
}

#[cfg(test)]
mod tests {
    use super::{measure, record};
    use std::io;

    #[test]
    fn measure_reports_samples_and_rme() {
        let mut index = 0usize;
        let result = measure(|| {
            index += 1;
            Ok::<usize, io::Error>(index)
        })
        .expect("measurement succeeds");
        assert!(result.samples >= 1);
        assert!(result.samples <= 200);
        assert!(result.rme_pct >= 0.0);
        assert_eq!(result.last_output, index);
    }

    #[test]
    fn throughput_record_is_canonical_json_shape() {
        let line = record(
            "compress.dickens.l3",
            "Compress · L3",
            "dickens",
            "MiB/s",
            None,
            512.5,
            0.25,
            42,
        );
        assert!(line.starts_with("{\"id\":\"compress.dickens.l3\","));
        assert!(line.contains("\"unit\":\"MiB/s\""));
        assert!(line.contains("\"value\":512.500000"));
        assert!(line.contains("\"rme_pct\":0.2500"));
        assert!(line.ends_with("\"samples\":42}}"));
    }

    #[test]
    fn ratio_record_marks_lower_is_better() {
        let line = record(
            "ratio.x-ray.l3",
            "Ratio · L3",
            "x-ray",
            "x",
            Some("lower"),
            1.0002,
            0.0,
            1,
        );
        assert!(line.contains("\"direction\":\"lower\""));
        assert!(line.contains("\"value\":1.000200"));
    }
}
