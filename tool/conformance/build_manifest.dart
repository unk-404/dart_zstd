// Builds test/conformance/manifest.json from the frames produced by
// tool/conformance/regenerate.sh.
//
// Usage:
//   dart tool/conformance/build_manifest.dart <corpus-dir> \
//       --zstd-version=1.6.0 --zstd-version-number=10600
//
// The manifest is the single source of truth for the VM conformance test:
// it records the generator, per-frame seed/options, file names, sizes and
// SHA-256 digests (implemented locally so this tool needs no dependencies).
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

void main(List<String> args) {
  final positional = <String>[];
  var zstdVersion = 'unknown';
  var zstdVersionNumber = 0;
  for (final arg in args) {
    if (arg.startsWith('--zstd-version=')) {
      zstdVersion = arg.substring('--zstd-version='.length);
    } else if (arg.startsWith('--zstd-version-number=')) {
      zstdVersionNumber =
          int.tryParse(arg.substring('--zstd-version-number='.length)) ?? 0;
    } else if (arg.startsWith('-')) {
      stderr.writeln('unknown option: $arg');
      exit(2);
    } else {
      positional.add(arg);
    }
  }
  if (positional.length != 1) {
    stderr.writeln(
      'usage: dart build_manifest.dart <corpus-dir> '
      '--zstd-version=<v> --zstd-version-number=<n>',
    );
    exit(2);
  }

  final dir = Directory(positional.single).absolute;
  final framesFile = File('${dir.path}/frames.tsv');
  if (!framesFile.existsSync()) {
    stderr.writeln('missing ${framesFile.path}; run regenerate.sh first');
    exit(1);
  }

  final frames = <Map<String, Object?>>[];
  final groups = <String, Map<String, Object?>>{};
  var totalZst = 0;
  var totalBin = 0;

  for (final line in framesFile.readAsLinesSync()) {
    if (line.trim().isEmpty) continue;
    final fields = line.split('\t');
    if (fields.length != 6) {
      stderr.writeln('malformed frames.tsv line: $line');
      exit(1);
    }
    final group = fields[0];
    final index = int.parse(fields[1]);
    final seed = int.parse(fields[2]);
    final options = fields[5].isEmpty ? <String>[] : fields[5].split(' ');
    final zstPath = 'zst/${fields[0]}-${index.toString().padLeft(3, '0')}.zst';
    final binPath = 'bin/${fields[0]}-${index.toString().padLeft(3, '0')}.bin';
    final zstBytes = File('${dir.path}/$zstPath').readAsBytesSync();
    final binBytes = File('${dir.path}/$binPath').readAsBytesSync();
    if (zstBytes.length != int.parse(fields[3]) ||
        binBytes.length != int.parse(fields[4])) {
      stderr.writeln('size mismatch for $zstPath / $binPath');
      exit(1);
    }

    frames.add(<String, Object?>{
      'group': group,
      'index': index,
      'seed': seed,
      'options': options,
      'zst': zstPath,
      'bin': binPath,
      'zstBytes': zstBytes.length,
      'binBytes': binBytes.length,
      'zstSha256': _sha256(zstBytes),
      'binSha256': _sha256(binBytes),
    });

    final summary = groups.putIfAbsent(
      group,
      () => <String, Object?>{
        'name': group,
        'options': options,
        'frameCount': 0,
        'firstSeed': seed,
        'lastSeed': seed,
        'zstBytes': 0,
        'binBytes': 0,
      },
    );
    summary['frameCount'] = (summary['frameCount']! as int) + 1;
    summary['lastSeed'] = seed;
    summary['zstBytes'] = (summary['zstBytes']! as int) + zstBytes.length;
    summary['binBytes'] = (summary['binBytes']! as int) + binBytes.length;
    totalZst += zstBytes.length;
    totalBin += binBytes.length;
  }

  final skipped = <Map<String, Object?>>[];
  final skippedFile = File('${dir.path}/skipped.tsv');
  if (skippedFile.existsSync()) {
    for (final line in skippedFile.readAsLinesSync()) {
      if (line.trim().isEmpty) continue;
      final fields = line.split('\t');
      if (fields.length < 3) continue;
      skipped.add(<String, Object?>{
        'group': fields[0],
        'seed': int.tryParse(fields[1]),
        'reason': fields[2],
      });
    }
  }

  final manifest = <String, Object?>{
    'schemaVersion': 1,
    'description':
        'Zstandard conformance corpus generated by the official zstd '
        'decodecorpus tool. Each .zst frame is paired with the exact '
        'plaintext in .bin.',
    'generatedAt': DateTime.now().toUtc().toIso8601String(),
    'generator': <String, Object?>{
      'name': 'decodecorpus',
      'zstdVersion': zstdVersion,
      'zstdVersionNumber': zstdVersionNumber,
      'upstream': 'https://github.com/facebook/zstd',
      'source': 'tests/decodecorpus.c',
      'build': 'make -C <zstd-src>/tests decodecorpus',
      'invocation':
          'decodecorpus -n1 -s<seed> -p<tmp> -o<tmp> <options> (one process '
          'per frame); frames rejected by reference `zstd -t` are skipped',
    },
    'decodeWindowLimit': 1 << 30,
    'totals': <String, Object?>{
      'frames': frames.length,
      'zstBytes': totalZst,
      'binBytes': totalBin,
      'totalBytes': totalZst + totalBin,
    },
    'groups': groups.values.toList(),
    'skipped': skipped,
    'frames': frames,
  };

  final out = File('${dir.path}/manifest.json');
  out.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(manifest)}\n',
  );
  stdout.writeln(
    'wrote ${out.path}: '
    '${frames.length} frames, ${totalZst + totalBin} bytes',
  );
}

